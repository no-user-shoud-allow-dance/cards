    <h2>Ihre Daten bleiben auf Ihrem Gerät</h2>
    <p>
        NSC ist eine reine Browser-App ohne Nutzerkonten. Es gibt keine
        Registrierung, und es werden keine Daten auf einem Server gespeichert.
        Alles, was anfällt, liegt lokal in Ihrem Browser:
    </p>
    <ul>
        <li>
            <strong>Local Storage:</strong> Lernfortschritt, Einstellungen
            (z. B. Pur-Modus), Lernzeit und Timer.
        </li>
        <li>
            <strong>IndexedDB:</strong> Stapel, die Sie selbst hochladen
            (Name, Ordner und Kartentext).
        </li>
    </ul>
    <p>
        Es werden keine Cookies gesetzt, keine Tracker oder Analyse-Dienste
        eingesetzt und keine Werbung angezeigt. Die Übertragung der Seite
        erfolgt verschlüsselt über HTTPS.
    </p>

